<?php
/**
 * Checked, bounded private archive delivery.
 *
 * @package FortressSecurityUltimate
 */

namespace Fortress\Security\Admin;

/** Keep native filesystem warnings out of ZIP responses. */
final class ZipDownload {
	/**
	 * Remove earlier output without ever flushing it into a binary attachment.
	 *
	 * @throws \RuntimeException If output has escaped or a buffer cannot be safely removed.
	 */
	public static function prepare_response(): void {
		self::assert_headers_unsent();
		try {
			while ( ob_get_level() > 0 ) {
				$level  = ob_get_level();
				$status = ob_get_status();
				$needed = PHP_OUTPUT_HANDLER_CLEANABLE | PHP_OUTPUT_HANDLER_REMOVABLE;
				if ( ! isset( $status['flags'] ) || ( $status['flags'] & $needed ) !== $needed ) {
					throw new \RuntimeException( 'FSU cannot remove an incompatible output buffer.' );
				}
				// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- A handler failure must become a generic error, never a path-bearing warning.
				if ( ! @ob_end_clean() || ob_get_level() >= $level ) {
					throw new \RuntimeException( 'FSU cannot remove an incompatible output buffer.' );
				}
			}
		} catch ( \Throwable $error ) {
			throw new \RuntimeException( 'FSU cannot start a clean archive response.' );
		}
		// Custom output handlers run during cleanup and may themselves emit bytes.
		self::assert_headers_unsent();
	}

	/**
	 * Check response state afresh after callbacks with unknown side effects.
	 *
	 * @throws \RuntimeException If the response has already started.
	 */
	private static function assert_headers_unsent(): void {
		if ( headers_sent() ) {
			throw new \RuntimeException( 'FSU cannot start a clean archive response.' );
		}
	}

	/**
	 * Discard ordinary shutdown output after the archive has been delivered.
	 *
	 * A small chunk size bounds pending buffered data. The buffer cannot be removed
	 * by ordinary shutdown flush loops. Direct SAPI writes and process termination
	 * remain outside this helper's control; this is not an output sandbox.
	 *
	 * @return bool Whether the response guard could be installed.
	 */
	public static function discard_following_output(): bool {
		// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- Starting a response guard must not append a native warning to the archive.
		return @ob_start( static fn(): string => '', 8192, PHP_OUTPUT_HANDLER_CLEANABLE | PHP_OUTPUT_HANDLER_FLUSHABLE );
	}

	/**
	 * Open a regular archive before the caller commits response headers.
	 *
	 * @param string $path Private archive generated by Exporter, never request input.
	 * @return array{stream:resource,size:int}
	 * @throws \RuntimeException If the archive cannot be safely delivered.
	 */
	public static function open( string $path ): array {
		if ( str_contains( $path, "\0" ) || ! preg_match( '~^(?:/|[A-Za-z]:[\\\\/])~', $path ) ) {
			throw new \RuntimeException( 'FSU archive is unavailable.' );
		}
		// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- Check native failure without exposing a private path.
		$before = @lstat( $path );
		if ( false === $before || ( $before['mode'] & 0170000 ) !== 0100000 || 1 !== $before['nlink'] ) {
			throw new \RuntimeException( 'FSU archive is unavailable.' );
		}
		// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged,WordPress.WP.AlternativeFunctions.file_system_operations_fopen -- Retain a local private descriptor; check failure before headers.
		$stream = @fopen( $path, 'rb' );
		if ( false === $stream ) {
			throw new \RuntimeException( 'FSU archive is unavailable.' );
		}
		$stat = fstat( $stream );
		if ( false === $stat || $stat['ino'] !== $before['ino'] || $stat['dev'] !== $before['dev'] || 1 !== $stat['nlink'] || $stat['size'] < 1 || $stat['size'] > 33619968 ) {
			// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose -- Release verified local descriptor.
			fclose( $stream );
			throw new \RuntimeException( 'FSU archive is unavailable.' );
		}
		return array(
			'stream' => $stream,
			'size'   => $stat['size'],
		);
	}

	/**
	 * Stream the archive with bounded memory and detect a short read.
	 *
	 * @param resource $stream Verified archive descriptor.
	 * @param int      $size Expected content length.
	 * @return bool
	 */
	public static function send( $stream, int $size ): bool {
		if ( ! is_resource( $stream ) ) {
			return false;
		}
		// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- A failed stream must not append native warning text to the binary response.
		$sent = @fpassthru( $stream );
		return $size === $sent;
	}

	/**
	 * Release only the caller-owned private archive, even on delivery failure.
	 *
	 * @param resource|null $stream Archive descriptor if opened.
	 * @param string|null   $path Verified private archive path, never request input.
	 */
	public static function cleanup( $stream, ?string $path ): void {
		if ( is_resource( $stream ) ) {
			// phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose -- Release verified local descriptor.
			fclose( $stream );
		}
		if ( null !== $path ) {
			// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged,WordPress.WP.AlternativeFunctions.unlink_unlink -- Cleanup failure must not corrupt the response; a failed deletion is retried by private storage cleanup.
			@unlink( $path );
		}
	}
}
